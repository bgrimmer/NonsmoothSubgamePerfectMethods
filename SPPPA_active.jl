# ==============================================================================
# SPPPA_active.jl
# ==============================================================================
# SPPPA with an active-set bundle.
#
# The retained bundle is variable size. After each planning subproblem, we keep:
#   * H_i entries with active μ_i multipliers: these carry y_i, f_i, z_{i+1}, τ_i.
#   * Q_{*,i} entries with active λ_i multipliers: these carry y_i, f_i, g_i.
#
# The implementation mirrors SPPPA_safe.jl and keeps its numerically safe OPPA
# fallback: solver statuses that might indicate unboundedness do not freeze the
# method by default.

using LinearAlgebra
using Convex
import SCS
import MathOptInterface as MOI

struct SPPPAActiveMethod <: AbstractMethod
    L::Float64
    active_tol::Float64
    accept_rel_tol::Float64
    accept_abs_tol::Float64
end

SPPPAActiveMethod(L::Float64; active_tol::Float64=1e-6,
                  accept_rel_tol::Float64=1e-4,
                  accept_abs_tol::Float64=1e-8) =
    SPPPAActiveMethod(L, active_tol, accept_rel_tol, accept_abs_tol)

# Convenience alias if you want the constructor name to match the file name.
const SPPPA_active = SPPPAActiveMethod

struct SPPPAActiveHHistory
    y::Vector{Float64}
    f::Float64
    z_next::Vector{Float64}
    tau::Float64
end

struct SPPPAActiveQHistory
    y::Vector{Float64}
    f::Float64
    g::Vector{Float64}
end

mutable struct SPPPAActiveState
    x::Vector{Float64}
    x0::Vector{Float64}
    n::Int

    tau_prime::Float64
    z_prime::Vector{Float64}
    tau_n::Float64

    h_history::Vector{SPPPAActiveHHistory}
    q_history::Vector{SPPPAActiveQHistory}

    y_last::Vector{Float64}
    y_star::Vector{Float64}
    frozen::Bool
end

function init_state(method::SPPPAActiveMethod, x0::Vector{Float64})
    return SPPPAActiveState(
        copy(x0), copy(x0), 0,
        0.0, copy(x0), 0.0,
        SPPPAActiveHHistory[], SPPPAActiveQHistory[],
        copy(x0), copy(x0), false
    )
end

get_query(method::SPPPAActiveMethod, state::SPPPAActiveState) = (state.x, method.L)
get_iterate(method::SPPPAActiveMethod, state::SPPPAActiveState) = state.frozen ? state.y_star : state.y_last

function spppa_active_best_y_and_f(h_entries::Vector{SPPPAActiveHHistory},
                                  q_entries::Vector{SPPPAActiveQHistory})
    f_m = Inf
    y_m = nothing

    for h in h_entries
        if h.f < f_m
            f_m = h.f
            y_m = h.y
        end
    end

    for q in q_entries
        if q.f < f_m
            f_m = q.f
            y_m = q.y
        end
    end

    return y_m, f_m
end

function spppa_active_multiplier_indices(vals::Vector{Float64}, tol::Float64)
    if isempty(vals)
        return Int[]
    end

    vmax = maximum(vals)
    threshold = tol * max(1.0, vmax)
    return [i for i in eachindex(vals) if vals[i] > threshold]
end

function update!(method::SPPPAActiveMethod, state::SPPPAActiveState, res::ProximalResult)
    if state.frozen
        return state
    end

    L = method.L

    # Compute the OPPA-type H entry generated by the new prox response.
    if state.n == 0
        tau_prev = 2.0 / L
        z_next = state.x0 - tau_prev * res.g
    else
        z_next = state.z_prime - (state.tau_n - state.tau_prime) * res.g
        tau_prev = state.tau_n
    end

    current_h = SPPPAActiveHHistory(copy(res.y), res.f_y, copy(z_next), tau_prev)
    current_q = SPPPAActiveQHistory(copy(res.y), res.f_y, copy(res.g))

    # Candidate bundle = previously active bundle + current observation.
    h_candidates = [state.h_history; current_h]
    q_candidates = [state.q_history; current_q]

    WH = length(h_candidates)
    WQ = length(q_candidates)

    y_m_any, f_m = spppa_active_best_y_and_f(h_candidates, q_candidates)
    y_m = y_m_any === nothing ? copy(res.y) : copy(y_m_any)

    Z = hcat([h.z_next - state.x0 for h in h_candidates]...)
    G = hcat([q.g for q in q_candidates]...)
    tau_vec = [h.tau for h in h_candidates]

    a = zeros(WH)
    for i in 1:WH
        h = h_candidates[i]
        a[i] = 0.5 * norm(h.z_next - state.x0)^2 + h.tau * (h.f - f_m)
    end

    b = zeros(WQ)
    for j in 1:WQ
        q = q_candidates[j]
        q_j = q.f - dot(q.g, q.y - state.x0)
        b[j] = q_j - f_m
    end

    # OPPA fallback corresponds to the current H entry.
    tau_fallback = tau_prev
    z_fallback = copy(z_next)

    tau_prime = tau_fallback
    z_prime = z_fallback
    accepted_step = false

    # --- SPPPA planning subproblem with separate H and Q bundles ---
    mu = Variable(WH)
    lam = Variable(WQ)
	
	println(WH,"  ",WQ)

    obj = dot(tau_vec, mu) + sum(lam)

    constraints = Constraint[
        mu >= 0,
        lam >= 0,
        sumsquares(Z * mu - G * lam) <= 2.0 * (dot(a, mu) + dot(b, lam))
    ]

    prob = maximize(obj, constraints)

    scs_opt = MOI.OptimizerWithAttributes(
        SCS.Optimizer,
        "eps_abs" => 1e-9,
        "eps_rel" => 1e-9,
        "max_iters" => 50000,
    )

    solve!(prob, scs_opt; silent_solver=true)

    mu_val = zeros(WH)
    lam_val = zeros(WQ)

    if prob.status == MOI.DUAL_INFEASIBLE ||
       prob.status == MOI.INFEASIBLE_OR_UNBOUNDED ||
       prob.status == MOI.OBJECTIVE_LIMIT

        # Safe behavior: do not freeze on numerical unboundedness. Use fallback.
        nothing

    elseif prob.status == MOI.OPTIMAL || prob.status == MOI.ALMOST_OPTIMAL
        mu_ev = evaluate(mu)
        lam_ev = evaluate(lam)

        mu_val = max.(0.0, mu_ev === nothing ? zeros(WH) : (mu_ev isa Number ? [mu_ev] : vec(mu_ev)))
        lam_val = max.(0.0, lam_ev === nothing ? zeros(WQ) : (lam_ev isa Number ? [lam_ev] : vec(lam_ev)))

        # Feasibility rounding.
        lhs = 0.5 * norm(Z * mu_val - G * lam_val)^2
        rhs = dot(a, mu_val) + dot(b, lam_val)

        if lhs > rhs
            if rhs > 1e-14
                alpha = rhs / lhs
                mu_val .*= alpha
                lam_val .*= alpha
            else
                mu_val .= 0.0
                lam_val .= 0.0
            end
        end

        tau_opt = dot(tau_vec, mu_val) + sum(lam_val)
        z_candidate = state.x0 + Z * mu_val - G * lam_val

        cert_lhs = 0.5 * norm(Z * mu_val - G * lam_val)^2
        cert_rhs = dot(a, mu_val) + dot(b, lam_val)

        accept_step =
            isfinite(tau_opt) &&
            all(isfinite, z_candidate) &&
            cert_rhs >= -1e-10 &&
            cert_lhs <= cert_rhs + 1e-8 * max(1.0, abs(cert_rhs)) &&
            tau_opt > tau_fallback * (1.0 + method.accept_rel_tol) + method.accept_abs_tol

        if accept_step
            tau_prime = tau_opt
            z_prime = z_candidate
            accepted_step = true
        end
    else
        @warn "SPPPAActive planning subproblem failed; using OPPA fallback" iteration=state.n status=prob.status
    end

    # Retain only active pieces from the accepted planning subproblem. If the
    # reoptimized step is not accepted, the effective subproblem is the OPPA
    # fallback, so retain only the current H and Q data.
    if accepted_step
        active_h = spppa_active_multiplier_indices(mu_val, method.active_tol)
        active_q = spppa_active_multiplier_indices(lam_val, method.active_tol)

        # Avoid empty bundles caused purely by multiplier tolerance. Empty H/Q
        # bundles are legal for storage, but keeping the largest entry of an
        # otherwise nonzero multiplier vector makes the next model less brittle.
        if isempty(active_h) && maximum(mu_val) > 0.0
            push!(active_h, argmax(mu_val))
        end
        if isempty(active_q) && maximum(lam_val) > 0.0
            push!(active_q, argmax(lam_val))
        end

        state.h_history = [h_candidates[i] for i in active_h]
        state.q_history = [q_candidates[j] for j in active_q]
    else
        state.h_history = SPPPAActiveHHistory[current_h]
        state.q_history = SPPPAActiveQHistory[current_q]
    end

    tau_next = tau_prime + (1.0 + sqrt(1.0 + 2.0 * L * tau_prime)) / L
    x_next = (tau_prime / tau_next) * y_m + ((tau_next - tau_prime) / tau_next) * z_prime

    state.x = x_next
    state.z_prime = z_prime
    state.tau_prime = tau_prime
    state.tau_n = tau_next
    state.y_last = copy(res.y)
    state.n += 1

    return state
end
